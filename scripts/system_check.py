"""Step 12: final end-to-end check of the whole system on this computer.

    python scripts/system_check.py           (or double-click system_check.bat)

Checks, in order, and writes a report to docs/system_check.md:
  1. Environment   Python and package versions; writes requirements-lock.txt (exact versions)
  2. Database      row counts of every table, data freshness
  3. Data quality  validation rules from NFR-3 (no negative counts, deaths <= cases, dates in order ...)
  4. REST API      every read endpoint answers correctly and within 3 seconds (NFR-1)
  5. Dashboard     page and layout load within 3 seconds
  6. Model         active model and its accuracy on unseen years
  7. Automation    last run of each scheduled job
  8. AI agents     which AI keys are set, questions answered so far, news signals (no AI calls are made)
  9. Tests         the full automated test suite (pytest)
"""

import importlib.metadata as md
import platform
import re
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from sqlalchemy import text  # noqa: E402

from denguewatch import __version__, config  # noqa: E402
from denguewatch.app import create_app  # noqa: E402
from denguewatch.db.connection import get_engine  # noqa: E402
from denguewatch.db.loader import table_counts  # noqa: E402

LIMIT_S = 3.0
results: list[tuple[str, str, bool, str]] = []   # (section, check, passed, detail)


def check(section: str, name: str, passed: bool, detail: str = "") -> None:
    results.append((section, name, bool(passed), detail))
    print(f"  [{'PASS' if passed else 'FAIL'}] {name}" + (f" - {detail}" if detail else ""))


def environment() -> None:
    print("1. Environment")
    check("Environment", "Python version", sys.version_info >= (3, 11), platform.python_version())
    lock, missing = [], []
    for line in (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines():
        m = re.match(r"\s*([A-Za-z0-9_.\-]+)(\[[^\]]+\])?", line)
        if not m or line.strip().startswith("#"):
            continue
        name = m.group(1)
        try:
            lock.append(f"{name}{m.group(2) or ''}=={md.version(name)}")
        except md.PackageNotFoundError:
            missing.append(name)
    (ROOT / "requirements-lock.txt").write_text(
        "# Exact versions used for the final evaluation (generated by scripts/system_check.py)\n"
        f"# Python {platform.python_version()} on {platform.system()} {platform.release()}, "
        f"{datetime.now():%Y-%m-%d}\n" + "\n".join(lock) + "\n", encoding="utf-8")
    check("Environment", "All required packages installed", not missing,
          f"{len(lock)} pinned in requirements-lock.txt" + (f"; missing {missing}" if missing else ""))


def database() -> dict:
    print("2. Database")
    counts = table_counts()
    check("Database", "All tables present", True, f"{len(counts)} tables")
    for t in ("states", "districts", "reports", "outbreaks", "weather_daily", "predictions", "model_versions"):
        check("Database", f"{t} has rows", counts.get(t, 0) > 0, f"{counts.get(t, 0):,}")
    with get_engine().connect() as conn:
        f = conn.execute(text("""SELECT (SELECT MAX(week_end) FROM reports),
                   (SELECT MAX(obs_date) FROM weather_daily WHERE data_type = 'observed'),
                   (SELECT MAX(obs_date) FROM weather_daily)""")).one()
    today = datetime.now().date()
    check("Database", "Weather is recent (observed within 7 days)", f[1] and (today - f[1]).days <= 7,
          f"observed to {f[1]}, forecast to {f[2]}")
    check("Database", "Latest IDSP report loaded", f[0] is not None, f"week ending {f[0]}")
    return counts


def data_quality() -> None:
    print("3. Data quality (NFR-3)")
    rules = {
        "No negative cases or deaths": "SELECT COUNT(*) FROM outbreaks WHERE cases < 0 OR deaths < 0",
        "Deaths never exceed cases": "SELECT COUNT(*) FROM outbreaks WHERE deaths > cases",
        "No duplicate outbreaks": "SELECT COUNT(*) - COUNT(DISTINCT outbreak_key) FROM outbreaks",
        "Every report week has 7 days": "SELECT COUNT(*) FROM reports WHERE week_end <> week_start + 6",
        "Weather values in physical range": """SELECT COUNT(*) FROM weather_daily WHERE precip_mm < 0
               OR temp_mean_c NOT BETWEEN -40 AND 55 OR rel_humidity_pct NOT BETWEEN 0 AND 100""",
        "Risk scores between 0 and 1": "SELECT COUNT(*) FROM predictions WHERE risk_score NOT BETWEEN 0 AND 1",
    }
    with get_engine().connect() as conn:
        for name, q in rules.items():
            bad = conn.execute(text(q)).scalar() or 0
            check("Data quality", name, bad == 0, f"{bad} violations")
        swapped, n = conn.execute(text("""SELECT COUNT(*) FILTER (WHERE start_date > reporting_date),
                                                 COUNT(*) FROM outbreaks""")).one()
        # Known typos in the source PDFs: tolerated if rare (they are noted in review_reasons).
        check("Data quality", "Start date not after reporting date (source typos <= 0.5%)", swapped <= 0.005 * n,
              f"{swapped} rows ({100 * swapped / n:.2f}%) have a reporting date before the start date in the PDF")
        matched, total, review = conn.execute(text("""SELECT COUNT(district_id), COUNT(*),
                COUNT(*) FILTER (WHERE needs_review) FROM outbreaks""")).one()
    check("Data quality", "Outbreaks matched to a district", matched / total >= 0.95,
          f"{100 * matched / total:.1f}% ({matched:,} of {total:,}); {review} flagged for review")


def api_and_dashboard() -> None:
    print("4. REST API (NFR-1: under 3 s)")
    client = create_app().test_client()
    with get_engine().connect() as conn:
        code = conn.execute(text("""SELECT d.census_code FROM outbreaks o JOIN districts d USING (district_id)
                                    GROUP BY 1 ORDER BY COUNT(*) DESC LIMIT 1""")).scalar()
    paths = ["/api/v1/", "/api/v1/health", "/api/v1/states", "/api/v1/districts", f"/api/v1/districts/{code}",
             f"/api/v1/districts/{code}/timeline", "/api/v1/outbreaks?limit=500", "/api/v1/outbreaks/summary?by=state",
             f"/api/v1/weather/{code}", "/api/v1/risk/current", f"/api/v1/risk/{code}", "/api/v1/model",
             "/api/v1/reports", "/api/v1/pipeline-runs", "/api/v1/signals", "/api/v1/schedule",
             "/api/v1/export/outbreaks.csv"]
    worst = 0.0
    for path in paths:
        t0 = time.perf_counter()
        r = client.get(path)
        secs = time.perf_counter() - t0
        worst = max(worst, secs)
        check("REST API", f"GET {path}", r.status_code == 200 and secs < LIMIT_S, f"{r.status_code}, {secs:.2f} s")
    r = client.post("/api/v1/admin/refresh?job=predict")
    check("REST API", "Admin endpoint refuses requests without token (NFR-5)", r.status_code == 401, str(r.status_code))
    r = client.get("/api/v1/outbreaks?state=Kerala' OR '1'='1")
    check("REST API", "SQL injection attempt is harmless (NFR-5)", r.status_code == 200 and r.get_json()["count"] == 0,
          f"{r.status_code}, {r.get_json().get('count')} rows")
    print("5. Dashboard")
    for path in ("/dashboard/", "/dashboard/_dash-layout"):
        t0 = time.perf_counter()
        r = client.get(path)
        secs = time.perf_counter() - t0
        check("Dashboard", f"GET {path}", r.status_code == 200 and secs < LIMIT_S, f"{r.status_code}, {secs:.2f} s")
    body = client.get("/dashboard/_dash-layout").get_data(as_text=True)
    tabs = ["Risk this week", "District explorer", "Compare districts", "Model & data", "Ask AI"]
    check("Dashboard", "All 5 pages present", all(t in body for t in tabs), ", ".join(tabs))


def model_and_automation() -> None:
    print("6. Model")
    client = create_app().test_client()
    m = client.get("/api/v1/model").get_json() or {}
    ev = m.get("evaluation") or {}
    pr, base = ev.get("test_pr_auc"), ev.get("test_base_rate")
    check("Model", "Active model beats chance on unseen years", bool(pr and base and pr > 2 * base),
          f"PR AUC {pr:.3f} vs chance {base:.3f} ({pr / base:.1f}x)" if pr and base else "metrics not found")
    print("7. Automation")
    sched = client.get("/api/v1/schedule").get_json() or {}
    for r in sched.get("results", []):
        check("Automation", f"{r['job']} ran recently", not r["overdue"], f"last success {r['last_success']}")


def agents() -> None:
    print("8. AI agents (no AI calls made)")
    check("AI agents", "AI key configured", bool(config.GEMINI_API_KEY or config.GROQ_API_KEY),
          ", ".join(n for n, k in (("Gemini", config.GEMINI_API_KEY), ("Groq", config.GROQ_API_KEY)) if k) or "none")
    with get_engine().connect() as conn:
        stats = dict(conn.execute(text("SELECT status, COUNT(*) FROM agent_queries GROUP BY 1")).all())
        sig = conn.execute(text("SELECT COUNT(*) FILTER (WHERE is_relevant), COUNT(*) FROM news_signals")).one()
    check("AI agents", "Questions answered and logged", stats.get("answered", 0) > 0,
          ", ".join(f"{k} {v}" for k, v in sorted(stats.items())))
    check("AI agents", "News agent has read articles", sig[1] > 0, f"{sig[0]} relevant of {sig[1]} articles")


def tests() -> None:
    print("9. Automated tests (pytest) - about 30 seconds")
    out = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"], cwd=ROOT,
                         capture_output=True, text=True)
    summary = (out.stdout.strip().splitlines() or ["no output"])[-1]
    check("Tests", "All automated tests pass", out.returncode == 0, summary.strip("= "))


def write_report() -> Path:
    passed = sum(r[2] for r in results)
    lines = ["# DengueWatch India - system check", "",
             f"Run {datetime.now():%Y-%m-%d %H:%M} on {platform.system()} {platform.release()}, "
             f"Python {platform.python_version()}, DengueWatch {__version__}.", "",
             f"**{passed} of {len(results)} checks passed.**", ""]
    section = None
    for sec, name, ok, detail in results:
        if sec != section:
            lines += ["", f"## {sec}", "", "| Check | Result | Detail |", "|---|---|---|"]
            section = sec
        lines.append(f"| {name} | {'PASS' if ok else '**FAIL**'} | {detail.replace('|', '/')} |")
    path = ROOT / "docs" / "system_check.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def main() -> int:
    print(f"DengueWatch India {__version__} - system check\n")
    for step in (environment, database, data_quality, api_and_dashboard, model_and_automation, agents, tests):
        try:
            step()
        except Exception as exc:  # noqa: BLE001 - report and continue with the next section
            check(step.__name__, f"{step.__name__} could not run", False, str(exc).splitlines()[0][:200])
    path = write_report()
    passed = sum(r[2] for r in results)
    print(f"\n{passed} of {len(results)} checks passed. Report: {path.relative_to(ROOT)}")
    failed = [f"{s}: {n}" for s, n, ok, _ in results if not ok]
    if failed:
        print("Failed:\n  " + "\n  ".join(failed))
    return 0 if not failed else 1


if __name__ == "__main__":
    sys.exit(main())
